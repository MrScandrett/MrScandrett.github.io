#!/usr/bin/env node
// Builds The Ages' Grand Timeline: the milestones of everything the site teaches, on one line.
//
// Sources:
//   data/ages-timeline.json   eras + hand-picked milestones, each linked to its lesson
//   The Ages' page script     artifacts and faith artifacts (with their 3D models) and era
//                             notes, read from the page so they live in one place
// Output: the <ol data-timeline> between the grand-timeline markers in the-ages.html.
// Milestones only: lesson timelines keep their detail; this is the one-line story.
//
//   node scripts/build-ages-timeline.mjs           write the page
//   node scripts/build-ages-timeline.mjs --check   fail if the page is out of date or a link/date is bad
//   node scripts/build-ages-timeline.mjs --report  list every item

import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const T = require('../assets/js/timeline.js');
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PAGE = 'lessons/humanities/the-ages.html';
const START = '<!-- grand-timeline:start (generated by scripts/build-ages-timeline.mjs; edit data/ages-timeline.json) -->';
const END = '<!-- grand-timeline:end -->';
const args = new Set(process.argv.slice(2));

const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const config = JSON.parse(read('data/ages-timeline.json'));
const lessons = new Map(JSON.parse(read('data/lessons.json')).lessons.map((l) => [l.url, l]));
const page = read(PAGE);

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const clean = (s) => String(s || '').replace(/\s+/g, ' ').trim();
function trimText(text, max) {
  text = clean(text);
  if (text.length <= max) return text;
  const cut = text.slice(0, max);
  const stop = cut.lastIndexOf('. ');
  return stop > 80 ? cut.slice(0, stop + 1) : cut.replace(/\s+\S*$/, '') + '…';
}
function lessonTitle(url) {
  const l = lessons.get(url);
  if (l) return l.title;
  const m = read(url).match(/<title>([^<]*)<\/title>/);
  return m ? clean(m[1]).split(/\s+[·|]\s+/)[0] : 'Open the lesson';
}

// Arrays from The Ages' page script (var name = [ … ];), evaluated as plain data.
function pageArray(name) {
  const at = page.indexOf(`var ${name} = [`);
  if (at === -1) throw new Error(`${PAGE}: can't find var ${name}`);
  let depth = 0;
  const i = page.indexOf('[', at);
  let j = i;
  for (; j < page.length; j++) {
    const c = page[j];
    if (c === '"' || c === "'" || c === '`') {
      for (j++; j < page.length && page[j] !== c; j++) if (page[j] === '\\') j++;
      continue;
    }
    if (c === '[' || c === '{') depth++;
    else if (c === ']' || c === '}') { depth--; if (!depth) break; }
  }
  return vm.runInNewContext(`(${page.slice(i, j + 1)})`);
}

const items = [];
const problems = [];
function add(ev) {
  const parsed = T.parseWhen(ev.when);
  if (!parsed) problems.push(`unreadable date "${ev.when}" (${ev.label})`);
  if (ev.lesson && !fs.existsSync(path.join(ROOT, ev.lesson))) problems.push(`missing lesson ${ev.lesson} (${ev.label})`);
  if (!ev.era && !config.colors[ev.strand]) problems.push(`unknown strand "${ev.strand}" (${ev.label})`);
  if (parsed) items.push({ ...ev, parsed });
}

const pageEras = new Map(pageArray('eras').map((e) => [e.key, e]));
for (const era of config.eras) {
  const notes = pageEras.get(era.key);
  add({ ...era, era: true, text: era.text || (notes ? `${notes.system} ${notes.shift}` : ''), anchor: '#era-atlas', anchorText: 'Open the Era Atlas' });
}
for (const ev of config.events) add(ev);
// Artifacts open their 3D model in the page's artifact viewer (data-ages-artifact).
for (const a of pageArray('artifacts')) add({ when: a.date, label: a.label, text: a.note, strand: 'Civilization', artifact: a.key, major: (config.majorArtifacts || []).includes(a.key) });
for (const a of pageArray('faithArtifacts')) add({ when: a.date, label: a.label, text: a.note, strand: 'Faith & Bible', artifact: a.key });
for (const ev of Object.values(config.christianEvents)) add({ ...ev, strand: 'Faith & Bible' });
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

items.sort((a, b) => a.parsed.start - b.parsed.start || (b.era ? 1 : 0) - (a.era ? 1 : 0) || a.parsed.end - b.parsed.end);
const fromPage = path.dirname(PAGE);
const li = (ev) => {
  const attrs = [`data-when="${esc(ev.when)}"`, `data-label="${esc(ev.label)}"`];
  if (ev.major) attrs.push('data-major');
  if (ev.artifact) attrs.push(`data-artifact="${esc(ev.artifact)}"`);
  if (ev.era) attrs.push('data-era', `data-key="${esc(ev.key)}"`);
  else attrs.push(`data-group="${esc(ev.strand)}"`, `data-color="${config.colors[ev.strand]}"`);
  const link = ev.lesson
    ? ` <a class="ages-gt-link" href="${esc(path.relative(fromPage, ev.lesson))}">${esc(lessonTitle(ev.lesson))} →</a>`
    : ev.artifact ? ` <button type="button" class="ages-gt-3d" data-ages-artifact="${esc(ev.artifact)}">View the 3D model</button>`
    : ev.anchor ? ` <a class="ages-gt-link" href="${ev.anchor}">${esc(ev.anchorText)} ↓</a>` : '';
  const text = ev.text ? ` — ${esc(trimText(ev.text, ev.era ? 320 : 260))}` : '';
  return `                <li ${attrs.join(' ')}><strong>${esc(ev.label)}</strong>${text}${link}</li>`;
};
const events = items.filter((e) => !e.era);
const lessonCount = new Set(events.map((e) => e.lesson).filter(Boolean)).size;
const block = [
  START,
  '              <ol class="ages-gt-list" data-timeline data-timeline-title="The story so far, on one line" data-timeline-scales="log time" data-timeline-search data-timeline-lanes="7" data-timeline-view="track">',
  ...items.map(li),
  '              </ol>',
  `              <p class="ages-gt-count">${events.length} milestones linked to ${lessonCount} lessons, plus 3D artifacts and Christian history. Each lesson has its own detailed timeline.</p>`,
  `              ${END}`
].join('\n');

if (/="undefined"|>undefined</.test(block)) { console.error('[ages-timeline] an attribute rendered as "undefined"'); process.exit(1); }
const a = page.indexOf('<!-- grand-timeline:start');
const b = page.indexOf(END);
if (a === -1 || b === -1) { console.error(`${PAGE}: grand-timeline markers not found`); process.exit(1); }
const next = page.slice(0, a) + block + page.slice(b + END.length);

if (args.has('--report')) {
  for (const ev of items) console.log(`${String(ev.when).padEnd(30)} ${(ev.era ? 'ERA' : ev.strand).padEnd(24)} ${ev.label}`);
}
console.log(`[ages-timeline] ${events.length} milestones, ${items.length - events.length} eras, ${lessonCount} lessons`);
if (args.has('--check')) {
  if (next !== page) { console.error('[ages-timeline] the-ages.html is out of date: run npm run build:ages-timeline'); process.exit(1); }
  console.log('[ages-timeline] up to date');
} else if (next !== page) {
  fs.writeFileSync(path.join(ROOT, PAGE), next);
  console.log(`[ages-timeline] wrote ${PAGE}`);
}
