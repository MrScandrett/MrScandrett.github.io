const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || chromium.executablePath(),headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1365,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto((process.env.APPLICATIONS_BASE_URL || 'http://localhost:8080') + '/applications.html');
await page.locator('.folder-button').first().waitFor();
assert.equal(await page.locator('#access-filter').inputValue(),'no-account');
assert.equal(await page.locator('[data-folder="steam"]').count(),0);
await page.screenshot({path:'/tmp/applications-desktop.png',fullPage:true});
await page.locator('[data-folder="music"]').click();
assert.ok(await page.locator('.app-card').count()>=3);
assert.equal(await page.locator('.app-card:not([data-access="no-account"])').count(),0);
await page.locator('#search-toggle').click();await page.locator('#app-search').fill('geoboard');
assert.equal(await page.locator('.app-card').count(),1,'Search should cross folders');
await page.reload();assert.equal(await page.locator('#app-search').inputValue(),'geoboard');
assert.equal(await page.locator('.app-card').count(),1);
await page.locator('#folder-back').click();
await page.locator('#access-filter').selectOption('classroom');
await page.locator('[data-folder="design3d"]').click();
await page.locator('#app-grid [data-tool-id="tinkercad"]').click();
await page.locator('#tinkercad-picker').waitFor({state:'visible'});await page.keyboard.press('Escape');
assert.equal(await page.locator('#tinkercad-picker').isVisible(),false);
await page.locator('#folder-back').click();await page.locator('#access-filter').selectOption('installed');
await page.locator('[data-folder="steam"]').click();await page.locator('[data-folder="steam-software"]').click();
assert.ok(await page.locator('.app-card').count()>0);
assert.equal(await page.locator('.app-card:not([data-access="installed"])').count(),0);
await page.locator('#access-filter').selectOption('no-account');
await page.locator('#app-search').fill('no-such-tool');
assert.ok(await page.locator('#apps-empty').isVisible());
await page.locator('#reset-app-filters').click();
assert.equal(await page.locator('#access-filter').inputValue(),'no-account');
await page.locator('#project-story > summary').click();
await page.locator('#project-story input').first().check();
const downloadPromise=page.waitForEvent('download');await page.locator('#project-story a[download]').click();
const download=await downloadPromise;assert.equal(download.suggestedFilename(),'story-plan.txt');
await page.reload();await page.locator('#project-story > summary').click();assert.ok(await page.locator('#project-story input').first().isChecked());
await page.locator('#clear-project-progress').click();assert.equal(await page.locator('#project-story input').first().isChecked(),false);
for(const width of [390,320]){
 await page.setViewportSize({width,height:844});await page.goto((process.env.APPLICATIONS_BASE_URL || 'http://localhost:8080') + '/applications.html');
 await page.locator('.folder-button').first().waitFor();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Folder overflow ${width}`);
 await page.locator('[data-folder="music"]').click();
 await page.locator('.app-save summary').first().click();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`App overflow ${width}`);
 await page.screenshot({path:`/tmp/applications-mobile-${width}.png`,fullPage:true});
}
await page.setViewportSize({width:1365,height:1000});
await page.goto((process.env.APPLICATIONS_BASE_URL || 'http://localhost:8080') + '/applications.html');
await page.locator('#access-filter').selectOption('all');
await page.locator('#grade-filter').selectOption('K-2');
await page.locator('.access-controls > a').click();
assert.equal(await page.locator('#access-filter').inputValue(),'all','Project jump preserves access');
assert.equal(await page.locator('#grade-filter').inputValue(),'K-2','Project jump preserves grade');
assert.equal(await page.locator('.project-path').count(),1,'Only age-matched paths shown');
await page.locator('#grade-filter').selectOption('all');
await page.locator('#access-filter').selectOption('account');
await page.locator('[data-folder="ai"]').click();
await page.locator('#app-grid [data-tool-id="claude"]').click();
assert.equal(await page.locator('#ai-confirm').isEnabled(),false);
await page.locator('#ai-pledge').check();assert.ok(await page.locator('#ai-confirm').isEnabled());
await page.keyboard.press('Escape');
await page.emulateMedia({colorScheme:'dark',reducedMotion:'reduce'});
await page.locator('#access-filter').selectOption('no-account');
await page.locator('#folder-back').click();
await page.locator('[data-folder="art"]').click();
await page.screenshot({path:'/tmp/applications-dark.png',fullPage:true});
assert.deepEqual(errors,[]);console.log('PASS: access filters, cross-folder search, URL restore, class modal, Steam navigation, safe reset, download, checklist persistence, 320/390px overflow, no page errors.');
await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
