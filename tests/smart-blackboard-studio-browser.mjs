import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { findChromium } from '../lib/find-chromium.mjs';
import { chooseShape, openControls } from './helpers/blackboard-studio.mjs';
const browser=await chromium.launch({executablePath:findChromium(),headless:true});
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8080/lessons/mathematics/geometry-and-trigonometry/smart-blackboard.html');
  await page.waitForSelector('.bb-studio');await page.evaluate(()=>document.fonts.ready);
  assert.equal(await page.locator('#bb-studio-panel').isVisible(),false);
  assert.equal(await page.locator('#bb-shape-menu').isVisible(),false);
  const canvas=page.locator('#chalk-canvas');
  assert.ok(await canvas.evaluate(el=>el.clientWidth>1000),'Canvas gets the full workspace width');
  await page.locator('#smart-blackboard-app').screenshot({path:'/tmp/blackboard-studio-default.png'});
  await page.locator('#bb-shapes-toggle').click();
  assert.equal(await page.locator('#bb-shape-menu').isVisible(),true);
  await page.locator('#bb-shapes-toggle').press('Escape');
  assert.equal(await page.locator('#bb-shape-menu').isVisible(),false);
  await chooseShape(page,'circle',null);
  assert.equal(await page.locator('#bb-shape-menu').isVisible(),false);
  assert.equal(await page.locator('#bb-select-tool').getAttribute('aria-pressed'),'true');
  const image=()=>canvas.evaluate(el=>el.toDataURL());
  const baseline=await image();
  await page.locator('#bb-ink-tool').click();
  const box=await canvas.boundingBox();
  await page.mouse.move(box.x+600,box.y+340);await page.mouse.down();await page.mouse.move(box.x+800,box.y+340,{steps:20});await page.mouse.up();
  assert.notEqual(await image(),baseline,'Ink tool draws with a physical pointer');
  await page.locator('#bb-eraser-tool').click();
  await page.mouse.move(box.x+700,box.y+340);await page.mouse.down();await page.mouse.up();
  assert.equal(await image(),baseline,'Eraser removes an ink stroke without changing geometry');
  await openControls(page,'air');await page.locator('#air-undo-ink').click();assert.notEqual(await image(),baseline);
  await page.locator('#bb-panel-close').click();assert.equal(await page.locator('#bb-studio-panel').isVisible(),false);
  await page.locator('#bb-object-controls').click();assert.equal(await page.locator('#bb-pane-geometry').isVisible(),true);
  await page.locator('#bb-panel-close').press('Escape');assert.equal(await page.locator('#bb-studio-panel').isVisible(),false);
  await page.locator('#bb-grid-toggle').click();assert.equal(await page.locator('#bb-grid-toggle').getAttribute('aria-pressed'),'true');
  await chooseShape(page,'3d-cube',null);await page.locator('#smart-blackboard-app').screenshot({path:'/tmp/blackboard-studio-cube.png'});
  assert.equal(await page.locator('#bb-orbit-reset').isVisible(),true);await page.locator('#bb-orbit-reset').click();
  await openControls(page,'geometry');await page.locator('#smart-blackboard-app').screenshot({path:'/tmp/blackboard-studio-properties.png'});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.locator('#bb-panel-close').click();await page.locator('#bb-shapes-toggle').click();
  await page.locator('#smart-blackboard-app').screenshot({path:'/tmp/blackboard-studio-mobile.png'});
  assert.equal(await page.locator('#btn-mode-circle').isVisible(),true);
  assert.deepEqual(errors,[]);
  console.log('Studio checks passed: full-width canvas, shape picker, contextual controls, pointer ink/eraser, drawers, keyboard and mobile.');
}finally{await browser.close();}
